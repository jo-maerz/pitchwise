    <strong>PDF mode: results may be restricted and inaccurate.</strong>
    The app cannot read the notes from a PDF, so it does not know which note you are meant to play.
    It takes the <em>nearest</em> note to what you play as the right one and shows how far you are from it.
    Playing a wrong note, or one that is far out of tune, is therefore judged against a different note than the score asks for,
    and nothing is checked against the page. These runs are not saved to your reports.
    For note-by-note checking, use a MusicXML file.
